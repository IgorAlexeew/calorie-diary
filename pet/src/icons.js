function pxIcon(name, size, cls){
  const m = PX_ICONS[name]; if (!m) return "";
  const w = Math.max(...m.map(r => r.length)), h = m.length, k = Math.max(w, h);
  let r = "";
  m.forEach((row, y) => [...row].forEach((v, x) => { if (v === "1") r += `<rect x="${x + (k - w) / 2}" y="${y + (k - h) / 2}" width="1.02" height="1.02"/>`; }));
  return `<svg class="pxi${cls ? " " + cls : ""}" viewBox="0 0 ${k} ${k}" width="${size || 16}" height="${size || 16}" fill="currentColor" aria-hidden="true">${r}</svg>`;
}
function pxEl(name, size, cls){ const s = document.createElement("span"); s.style.display = "inline-flex"; s.innerHTML = pxIcon(name, size, cls); return s; }
